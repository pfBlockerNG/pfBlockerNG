# ADR-38: the dedicated package syslog file (from the <logging> block). The
# !pfblockerng syslog.d drop-in routes ONLY program=pfblockerng records here, so
# every line in this file is one exported security event.
PFB_SYSLOG_LOG = "/var/log/pfblockerng_syslog.log"
# Generated by pfSense core from the <logging> block (routing + rotation).
SYSLOG_DROPIN = "/var/etc/syslog.d/pfblockerng_syslog.log.conf"
NEWSYSLOG_ENTRY = "/var/etc/newsyslog.conf.d/pfblockerng_syslog.log.conf"
# General System log — export events must NOT appear here (excluded by the drop-in).
SYSTEM_LOG = "/var/log/system.log"

# pfBlockerNG CSV security logs (unchanged by syslog export).
PFB_LOGDIR = "/var/log/pfblockerng"
DNSBL_LOG = f"{PFB_LOGDIR}/dnsbl.log"
IP_BLOCK_LOG = f"{PFB_LOGDIR}/ip_block.log"

# Config path for the syslog export toggle (under the General settings section).
CFG_GENERAL = "installedpackages/pfblockerng/config/0"

# A test IP range whose pfBlockerNG block rule we trigger traffic against.
# RFC 5737 TEST-NET-3 (203.0.113.0/24) — not routable, but pf still blocks
# an outbound connection attempt if it matches an alias table for that range.
TEST_IP_BLOCK_RANGE = "203.0.113.0/24"
TEST_IP_BLOCK_DST = "203.0.113.1"

# Settle budget for the tail_pfb → daemon → syslogd → file path.
FILTERLOG_SETTLE_SECS = 5.0
EVENT_WAIT_SECS = 15.0
# IP action tokens any IP security event may carry (block/permit/match).
IP_ACT_TOKENS = ("act=block", "act=pass", "act=match")


# --------------------------------------------------------------------------- #
# Module-scoped fixture: deploy once, inject DNSBL + IP, reload (syslog OFF)
# --------------------------------------------------------------------------- #


@pytest.fixture(scope="module")
def deployed_vm(
    smoke_vm: SmokeVM,
    client_vm: SmokeVM,
    stub_dns: _StubDnsServer,
) -> Iterator[SmokeVM]:
    """Deploy the branch .pkg once; wire DNSBL + IP; reload with syslog OFF.

    Given: the smoke VM is booted and the branch .pkg is available.
    When:  we deploy, wire DNSBL (unique blocked domain, VIP) + one IP block feed
           (RFC 5737), and do a full reload with syslog export OFF (the default).
           The reload runs sync_package_pfblockerng, which materializes the syslog
           routing drop-in (ADR-38) and (re)starts the filterlog daemon tailing
           filter.log + dnsbl.log + dns_reply.log.
    Then:  the module VM is ready for the per-test assertions.
    """
    if not os.environ.get("SMOKE_PKG"):
        pytest.skip("SMOKE_PKG not set — no built .pkg to deploy")

    h.deploy(smoke_vm)
    h.use_system_dns_upstream(smoke_vm)
    h.ensure_dnsbl_vip(smoke_vm)

    _dnsbl_domain = h.unique_domain("pfbsyslogdnsbl")
    _dnsbl_feed_path = h.write_local_feed(smoke_vm, "pfb_syslog_dnsbl.txt", f"{_dnsbl_domain}\n")
    h.inject(
        smoke_vm,
        h.DnsblCase(
            aliasname="pfb_syslog_test",
            feed_url=_dnsbl_feed_path,
            mode=h.DnsblMode.VIP,
            header="pfb_syslog_dnsbl",
            hsts=False,  # explicit — test domain is not HSTS-preloaded
        ),
    )

    # IP feed (alias only; default WAN rule). NOTE: the IP-block LIVE leg is deferred
    # (see test_syslog_on_ip_block_event_exported xfail + follow-up). A LAN-interface
    # rule was found to break ALL civm->pfSense traffic (the LAN filter rebuild drops
    # the permissive allow), and a WAN rule to an unreachable TEST-NET IP never logs;
    # a clean live test needs a reachable non-infra target + a WAN/floating rule.
    _ip_feed_path = h.write_local_feed(smoke_vm, "pfb_syslog_ip.txt", f"{TEST_IP_BLOCK_RANGE}\n")
    h.inject(
        smoke_vm,
        h.IpCase(
            aliasname="pfb_syslog_iptest",
            feed_url=_ip_feed_path,
            action="Deny_Outbound",
            family="v4",
            header="pfb_syslog_ip",
        ),
    )

    # Syslog export OFF (the default) at module start.
    _set_syslog_enabled(smoke_vm, on=False)

    # Full reload: installs DNSBL + IP block, materializes the syslog routing, and
    # starts the filterlog daemon.
    h.reload(smoke_vm, "update")

    # Precondition: the civm -> pfSense LAN link is healthy (civm can resolve via
    # pfSense). All cases drive traffic from civm, so a dead LAN link must surface
    # as a clear "civm/LAN link" diagnosis here, not a bare dig timeout deep in a test.
    h.assert_link_health(client_vm, smoke_vm, control_name=h.unique_domain())

    # civm's ACTUAL LAN IP (static or dynamic lease) — the expected qip/source in
    # the export events. Captured once the link is proven healthy.
    _civm_ip = _civm_lan_ip(client_vm)

    # Precondition: DNSBL is blocking the test domain (VIP shape), as seen by the
    # civm client behind the firewall (the realistic consumer path).
    ans = h.dns_probe_client(client_vm, _dnsbl_domain, "A")
    if not h.is_vip(ans):
        pytest.skip(
            f"DNSBL VIP block not observed for {_dnsbl_domain} (got {ans}) — "
            f"DNSBL precondition failed; skipping syslog tests"
        )

    smoke_vm._pfb_dnsbl_domain = _dnsbl_domain  # type: ignore[attr-defined]
    smoke_vm._pfb_civm_ip = _civm_ip  # type: ignore[attr-defined]
    yield smoke_vm


