package dnsbl_test

// The Core-input goldens of both decider corpora (issue #4036, plan section 4): for every parity scenario
// (tests/dns_proxy/fixtures/parity) and every build-oracle row the file input builds
// (go/pfb_dns_gateway/decider/testdata/pfb_unbound_build_oracle.json, want not null), the dnsbl/* resources the assembler
// publishes from the same module directory, into a fresh store: each body's lines and metadata, and the rows it left
// out. pfB-DNS's Core-input runner serves them; this test keeps them equal to what the assembler writes. Regenerate with
// `go test ./dnsbl -run CoreInputGoldens -update`.
//
// The module directory maps onto a Set as the file input reads it: each manifest feed's raw file, UTF-8 decoded with
// replacement and CR removed, one row per line (dnsblFileLineReader); the manifest config's lists, top1m_enabled and
// builtin_log_flag; TOP1M from config.top1m_list when the manifest still carries it, else pfb_py_top1m.txt, each line
// stripped, only while top1m_enabled; the SafeSearch rows of 3 or 5 fields of pfb_py_ss.txt (loadSafesearchDb); the PSL
// text of dnsbl_psl (the oracle: its pfb_py_psl). A row whose build refuses the manifest has no Core input: the
// Core Updater never publishes such a manifest. config.regex_cap is a setting, not data, and the ini is not read here.

